XMDS2_RK9_STAGES = 16

# Diffrax 0.7.2 requires b_error even with ConstantStepSize. XMDS2's fixed RK9
# has no embedded estimate, so zero weights explicitly represent "no estimate".
# An adaptive step-size controller must not be used with this tableau.
_NO_EMBEDDED_ERROR = np.zeros(XMDS2_RK9_STAGES, dtype=np.float64)

if not np.allclose(XMDS2_RK9_A.sum(axis=1), XMDS2_RK9_C, rtol=0.0, atol=5e-14):
    raise ValueError("XMDS2 RK9 stage rows do not sum to their abscissae")
if not np.isclose(XMDS2_RK9_B_SOL.sum(), 1.0, rtol=0.0, atol=5e-14):
    raise ValueError("XMDS2 RK9 solution weights do not sum to one")


XMDS2_RK9_TABLEAU = diffrax.ButcherTableau(
    c=XMDS2_RK9_C[1:].copy(),
    a_lower=tuple(XMDS2_RK9_A[i, :i].copy() for i in range(1, 16)),
    b_sol=XMDS2_RK9_B_SOL.copy(),
    b_error=_NO_EMBEDDED_ERROR,
)


class XMDS2RK9(diffrax.AbstractERK, diffrax.AbstractStratonovichSolver):
    """XMDS2 fixed-step 16-stage ninth-order explicit Runge--Kutta method.

    The deterministic order is 9. XMDS2's generic stochastic interpretation
    has strong order 1/2 and treats a Wiener rate as constant during each fixed
    step. Diffrax expresses this with a ``ControlTerm`` carrying the prescribed
    total increment. For the project's state-independent additive diffusion,
    Ito and Stratonovich forms coincide.

    This solver has no embedded error estimate and is only intended for
    ``diffrax.ConstantStepSize``.

    G. R. Dennis, J. J. Hope, and M. T. Johnsson, "XMDS2: Fast, scalable
    simulation of coupled stochastic partial differential equations,"
    Computer Physics Communications 184 (2013), 201--208.

    Ch. Tsitouras, "Optimized explicit Runge--Kutta pair of orders 9(8),"
    Applied Numerical Mathematics 38 (2001), 123--134. The fixed-step
    solution tableau here is transcribed from XMDS2, rather than reconstructed
    from the adaptive pair in the paper.
    """

    tableau: ClassVar[diffrax.ButcherTableau] = XMDS2_RK9_TABLEAU
    interpolation_cls: ClassVar[
        Callable[..., diffrax.ThirdOrderHermitePolynomialInterpolation]
    ] = diffrax.ThirdOrderHermitePolynomialInterpolation.from_k

    def order(self, terms):
        del terms
        return 9

    def strong_order(self, terms):
        del terms
        return 0.5
