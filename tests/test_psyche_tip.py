"""Scientific checks for event extraction; requires the pinned local kernels."""

import unittest

import numpy as np
import spiceypy as raw
from tudatpy.interface import spice

from psyche_mission_events_reconstruction.kernels import (
    covers,
    inspect_spk,
    kernel_paths,
    loaded_kernels,
    selected_segment,
    state_si,
)
from psyche_mission_events_reconstruction.orbit import hyperbolic_diagnostics


class HyperbolaChecks(unittest.TestCase):
    def test_known_hyperbola_and_rotated_asymptote(self):
        # mu=1, rp=1, vp=2 gives C3=2, e=3 analytically.
        y = np.array([1.0, 0, 0, 0, 2.0, 0])
        expected = np.sqrt(2) * np.array([-1 / 3, np.sqrt(8) / 3, 0])
        angle = 0.7
        rotation = np.array(
            [[1, 0, 0], [0, np.cos(angle), -np.sin(angle)], [0, np.sin(angle), np.cos(angle)]]
        )
        for matrix in (np.eye(3), rotation):
            d = hyperbolic_diagnostics(np.r_[matrix @ y[:3], matrix @ y[3:]], 1)
            self.assertAlmostEqual(d["c3_m2_s2"], 2)
            self.assertAlmostEqual(d["eccentricity"], 3)
            np.testing.assert_allclose(d["outgoing_vinfinity_si"], matrix @ expected, atol=1e-14)

    def test_nonhyperbolic_and_invalid_inputs_rejected(self):
        for state, mu in [
            (np.array([1.0, 0, 0, 0, 1.0, 0]), 1),
            (np.zeros(6), 1),
            (np.full(6, np.nan), 1),
            (np.ones(6), -1),
        ]:
            with self.assertRaises(ValueError):
                hyperbolic_diagnostics(state, mu)


class MissionChecks(unittest.TestCase):
    def test_coverage_units_publication_and_origin_translation(self):
        paths = kernel_paths()
        with loaded_kernels(paths):
            # The shared/separate-pool handling must not duplicate loaded SPKs.
            self.assertEqual(raw.ktotal("SPK"), 2)
            tip = spice.convert_date_string_to_ephemeris_time("2023-10-13 15:30:34 UTC")
            metadata = inspect_spk(paths[-1])
            windows = metadata["coverage"]["-255"]
            self.assertTrue(covers(windows, tip))
            start = windows[0]["start"]["et_tdb_s"]
            self.assertFalse(covers(windows, start - 1))
            self.assertEqual(selected_segment(-255, tip)["centre"], 399)
            with self.assertRaisesRegex(Exception, "SPKINSUFFDATA"):
                state_si(-255, 399, start - 1)
            state = state_si(-255, 399, tip)
            independent_units = raw.spkezr("-255", tip, "J2000", "NONE", "399")[0] * 1000
            np.testing.assert_allclose(state, independent_units, rtol=0, atol=1e-8)
            translated = state + state_si(399, 10, tip)
            np.testing.assert_allclose(translated, state_si(-255, 10, tip), rtol=0, atol=1e-3)
            d = hyperbolic_diagnostics(state, spice.get_body_gravitational_parameter("399"))
            # External post-flight Table 1, not values generated by this code.
            self.assertLess(abs(d["c3_km2_s2"] - 34.0023), 5e-5)
            self.assertLess(abs(d["rla_deg"] - 113.7071), 1e-4)
            self.assertLess(abs(d["dla_deg"] - 28.0153), 1e-4)
        self.assertEqual(raw.ktotal("ALL"), 0)
        self.assertEqual(spice.get_total_count_of_kernels_loaded(), 0)


if __name__ == "__main__":
    unittest.main()
